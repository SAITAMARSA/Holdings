import { chromium } from "playwright";
const shots = process.env.SHOTS_DIR ?? "./e2e-shots";
import { mkdirSync } from "node:fs"; mkdirSync(shots, { recursive: true });
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" }).catch(() => chromium.launch());
const page = await browser.newPage({ viewport: { width: 390, height: 780 } });
const errors = []; page.on("pageerror", e => errors.push(e.message)); page.on("console", m => m.type()==="error" && errors.push(m.text()));
await page.goto("http://localhost:8787/");
await page.fill('input[placeholder="Your name"]', "Thabo");
await page.click("text=isiZulu");
await page.screenshot({ path: `${shots}/1-onboarding.png` });
await page.click("text=Next");
await page.fill('input[placeholder="Twin\'s name"]', "Zee");
